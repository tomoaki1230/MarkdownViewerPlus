export const DEFAULT_THEME_ID = 'standard';

/** 配色（'light' / 'dark'）のテーマ一覧 */
export function themesFor(scheme) {
  return scheme === 'dark' ? DARK_THEMES : LIGHT_THEMES;
}

/** ID からテーマを探す（見つからなければ標準） */
export function findTheme(scheme, id) {
  const list = themesFor(scheme);
  return list.find((t) => t.id === id) ?? list[0];
}

export function isThemeId(scheme, id) {
  return themesFor(scheme).some((t) => t.id === id);
}

/** テーマの色を CSS 変数の組にする（bgSub → --bg-sub） */
export function themeCssVars(theme) {
  const vars = {};
  for (const key of THEME_KEYS) {
    vars[`--${key.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`)}`] = theme.colors[key];
  }
  return vars;
}
